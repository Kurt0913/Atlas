import 'dart:typed_data';
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import '../database/app_database.dart';
import '../models/task_item.dart';

// ── Shared palette ────────────────────────────────────────────────────────
const _gold   = PdfColor.fromInt(0xFF143D2B);
const _dark   = PdfColor.fromInt(0xFF0F1914);
const _muted  = PdfColor.fromInt(0xFF5A6E64);
const _border = PdfColor.fromInt(0xFFDDE6E0);
const _bg     = PdfColor.fromInt(0xFFF6F8F6);
const _body   = PdfColor.fromInt(0xFF1A2620);
const _footer = PdfColor.fromInt(0xFF8C9E95);

// ── Style helpers ─────────────────────────────────────────────────────────
pw.TextStyle _style({
  double size = 11,
  pw.FontWeight weight = pw.FontWeight.normal,
  PdfColor color = _dark,
}) =>
    pw.TextStyle(fontSize: size, fontWeight: weight, color: color);

pw.Divider _divider({double thickness = 0.5}) =>
    pw.Divider(color: _border, thickness: thickness);

// Table column helper — wraps Expanded or fixed-width SizedBox
pw.Widget _col(
  String text, {
  int? flex,
  double? width,
  pw.TextAlign align = pw.TextAlign.left,
  double size = 10,
  pw.FontWeight weight = pw.FontWeight.normal,
  PdfColor color = _muted,
}) {
  final child = pw.Text(
    text,
    textAlign: align,
    style: _style(size: size, weight: weight, color: color),
  );
  if (width != null) return pw.SizedBox(width: width, child: child);
  return pw.Expanded(flex: flex ?? 1, child: child);
}

class InvoiceService {
  static final InvoiceService instance = InvoiceService._init();
  InvoiceService._init();

  /// Fetches all done tasks in [dateFrom]..[dateTo], grouped by currency,
  /// generates a PDF invoice, and opens the native print/share dialog.
  Future<void> exportInvoicePdf({
    required DateTime dateFrom,
    required DateTime dateTo,
  }) async {
    final tasks = await AppDatabase.instance.getInvoiceTasks(
      dateFrom: dateFrom,
      dateTo: dateTo,
    );
    final pdf = await _buildPdf(tasks, dateFrom, dateTo);
    await Printing.sharePdf(
      bytes: pdf,
      filename:
          'atlas_invoice_${_fmtFile(dateFrom)}_${_fmtFile(dateTo)}.pdf',
    );
  }

  Future<Uint8List> _buildPdf(
    List<TaskItem> tasks,
    DateTime dateFrom,
    DateTime dateTo,
  ) async {
    final doc = pw.Document();

    final Map<String, List<TaskItem>> byCurrency = {};
    for (final t in tasks) {
      byCurrency.putIfAbsent(t.clientCurrency, () => []).add(t);
    }

    final dateFmt = DateFormat('MMMM d, yyyy');
    final numFmt  = NumberFormat('#,##0.00');

    doc.addPage(pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.symmetric(horizontal: 48, vertical: 52),
      build: (ctx) => [
        _buildHeader(dateFmt, dateFrom, dateTo),
        pw.SizedBox(height: 8),
        _divider(thickness: 1.5),
        pw.SizedBox(height: 20),
        if (tasks.isEmpty)
          pw.Center(
            child: pw.Text(
              'No completed tasks found in this date range.',
              style: _style(color: _muted),
            ),
          )
        else ...[
          for (final currency in byCurrency.keys)
            _buildCurrencySection(
                currency, byCurrency[currency]!, numFmt),
          _divider(thickness: 1),
          pw.SizedBox(height: 8),
          pw.Center(
            child: pw.Text(
              'Generated by Atlas · '
              '${tasks.length} task${tasks.length == 1 ? '' : 's'} completed',
              style: _style(size: 9, color: _footer),
            ),
          ),
        ],
      ],
    ));

    return doc.save();
  }

  // ── Page sections ─────────────────────────────────────────────────────

  pw.Widget _buildHeader(
      DateFormat dateFmt, DateTime dateFrom, DateTime dateTo) {
    return pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text('ATLAS',
                style: _style(
                    size: 28,
                    weight: pw.FontWeight.bold,
                    color: _gold)
                    .copyWith(letterSpacing: 6)),
            pw.SizedBox(height: 4),
            pw.Text('Freelance Operations',
                style: _style(size: 11, color: _muted)),
          ],
        ),
        pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.end,
          children: [
            pw.Text('INVOICE',
                style: _style(
                    size: 22, weight: pw.FontWeight.bold, color: _dark)),
            pw.SizedBox(height: 4),
            pw.Text(
                'Period: ${dateFmt.format(dateFrom)} – ${dateFmt.format(dateTo)}',
                style: _style(size: 10, color: _muted)),
            pw.Text('Generated: ${dateFmt.format(DateTime.now())}',
                style: _style(size: 10, color: _muted)),
          ],
        ),
      ],
    );
  }

  pw.Widget _buildCurrencySection(
    String currency,
    List<TaskItem> tasks,
    NumberFormat numFmt,
  ) {
    final total = tasks.fold<double>(0, (s, t) => s + t.clientRate);

    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        // Currency header bar
        pw.Container(
          padding: const pw.EdgeInsets.symmetric(horizontal: 12, vertical: 8),
          decoration: pw.BoxDecoration(
            color: _bg,
            borderRadius: pw.BorderRadius.circular(8),
            border: pw.Border.all(color: _border),
          ),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text('$currency Earnings',
                  style: _style(
                      size: 13, weight: pw.FontWeight.bold, color: _dark)),
              pw.Text('$currency ${numFmt.format(total)}',
                  style: _style(
                      size: 16, weight: pw.FontWeight.bold, color: _gold)),
            ],
          ),
        ),
        pw.SizedBox(height: 10),

        // Table header
        pw.Row(children: [
          _col('Task',      flex: 4, weight: pw.FontWeight.bold),
          _col('Client',    flex: 2, weight: pw.FontWeight.bold),
          _col('Completed', flex: 1, weight: pw.FontWeight.bold,
              align: pw.TextAlign.center),
          _col('Amount',    width: 80, weight: pw.FontWeight.bold,
              align: pw.TextAlign.right),
        ]),
        _divider(),

        // Task rows
        for (final task in tasks)
          pw.Padding(
            padding: const pw.EdgeInsets.symmetric(vertical: 5),
            child: pw.Row(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                _col(task.title,           flex: 4, size: 11, color: _body),
                _col(task.clientName,      flex: 2, size: 11, color: _dark),
                _col(task.dueDate,         flex: 1, size: 10, color: _muted,
                    align: pw.TextAlign.center),
                _col(numFmt.format(task.clientRate), width: 80, size: 11,
                    weight: pw.FontWeight.bold, color: _dark,
                    align: pw.TextAlign.right),
              ],
            ),
          ),

        _divider(),
        pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.end,
          children: [
            pw.Text('Subtotal: $currency ${numFmt.format(total)}',
                style: _style(
                    size: 12, weight: pw.FontWeight.bold, color: _gold)),
          ],
        ),
        pw.SizedBox(height: 20),
      ],
    );
  }

  String _fmtFile(DateTime dt) => DateFormat('yyyyMMdd').format(dt);
}
